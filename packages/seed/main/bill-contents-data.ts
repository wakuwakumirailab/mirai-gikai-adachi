export function createBillContents(
  insertedBills: { id: string; name: string; published_at: string | null }[]
) {
  return billContentsWithBillName.map((content) => {
    const bill = insertedBills.find(
      (b) =>
        b.name === content.bill_name &&
        b.published_at?.slice(0, 10) === content.published_at
    );
    if (!bill) {
      throw new Error(
        `Bill not found for content: ${content.bill_name} (${content.published_at})`
      );
    }

    return {
      bill_id: bill.id,
      difficulty_level: content.difficulty_level,
      title: content.title,
      summary: content.summary,
      content: content.content,
      is_preliminary_source: content.is_preliminary_source ?? false,
      source_references: (content.source_references ?? []) as unknown as Json,
    };
  });
}
