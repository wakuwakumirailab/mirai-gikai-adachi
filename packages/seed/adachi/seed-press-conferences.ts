async function main() {
  const supabase = createAdminClient();

  for (const pc of DATA) {
    console.log(`\n[${pc.slug}] ${pc.title}`);

    const { data: existing } = await supabase
      .from("press_conferences")
      .select("id")
      .eq("slug", pc.slug)
      .maybeSingle();

    if (existing) {
      console.log(`  → スキップ（既存）`);
      continue;
    }

    const { data: pcRow, error: pcErr } = await supabase
      .from("press_conferences")
      .insert({
        slug: pc.slug,
        title: pc.title,
        held_at: pc.heldAt,
        youtube_url: pc.youtubeUrl,
        status: pc.status,
      })
      .select()
      .single();

    if (pcErr || !pcRow) {
      throw new Error(`press_conferences INSERT 失敗: ${pcErr?.message}`);
    }

    for (const item of pc.items) {
      const { data: itemRow, error: itemErr } = await supabase
        .from("press_conference_items")
        .insert({
          press_conference_id: pcRow.id,
          item_type: item.itemType,
          order_index: item.orderIndex,
          title: item.title,
          summary: item.summary,
          summary_easy: item.summaryEasy ?? null,
          material_url: item.materialUrl ?? null,
        })
        .select()
        .single();

      if (itemErr || !itemRow) {
        throw new Error(
          `press_conference_items INSERT 失敗: ${itemErr?.message}`
        );
      }

      if (item.turns.length > 0) {
        const { error: turnsErr } = await supabase
          .from("press_conference_turns")
          .insert(
            item.turns.map((t) => ({
              press_conference_item_id: itemRow.id,
              speaker: t.speaker,
              speaker_name: t.speakerName,
              content: t.content,
              order_index: t.orderIndex,
            }))
          );

        if (turnsErr) {
          throw new Error(
            `press_conference_turns INSERT 失敗: ${turnsErr.message}`
          );
        }
      }
    }

    console.log(`  → 投入完了（items: ${pc.items.length}）`);
  }

  console.log("\n✅ 完了");
}

main().catch((e) => {
  console.error(e);
  process.exit(1);
});
